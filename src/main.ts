/// <reference types="vite/client" />
import "./styles.css";
import { parseInput } from "./lib/parse";
import { ALPHAS, EXAMPLE_BATCH, analyzeBatch } from "./lib/triage";
import type { ModelFile } from "./lib/model";
import type { Actions, AppState, Benchmark, TabId } from "./ui/context";
import { esc, pct } from "./ui/dom";
import { renderPredict } from "./ui/predict";
import { renderPareto } from "./ui/pareto";
import { renderValidation } from "./ui/validation";
import { renderMethods } from "./ui/methods";

const TABS: { id: TabId; label: string; blurb: string }[] = [
  { id: "predict", label: "Predict", blurb: "batch triage with abstention" },
  { id: "pareto", label: "Pareto", blurb: "which trade-offs are real" },
  { id: "validation", label: "Validation", blurb: "does it generalise" },
  { id: "methods", label: "Methods", blurb: "how it works, and its limits" },
];

const root = document.getElementById("root")!;

function boot(): void {
  root.innerHTML = `<div class="splash">loading model…</div>`;
  const base = import.meta.env.BASE_URL;
  fetch(`${base}model.json`)
    .then((r) => {
      if (!r.ok) throw new Error(`model.json: HTTP ${r.status}`);
      return r.json() as Promise<ModelFile>;
    })
    .then((model) => start(model))
    .catch((err) => {
      root.innerHTML = `<div class="splash"><h2>Could not load the model</h2>
        <p class="hint">${esc(String(err))}</p>
        <p class="hint">The app needs <code>public/model.json</code>, generated by
        <code>python3 scripts/train.py</code>. If it is missing from the deployed build,
        the model file was not committed or the base path is wrong.</p></div>`;
    });
  fetch(`${base}benchmark.json`)
    .then((r) => (r.ok ? r.json() : null))
    .then((b: Benchmark | null) => {
      if (!b) return;
      if (!state) {
        pendingBenchmark = b;
        return;
      }
      state.benchmark = b;
      updateDial();
      if (tab === "validation") render();
    })
    .catch(() => undefined);
}

let state: AppState;
let tab: TabId = "predict";
let pendingBenchmark: Benchmark | null = null;
let actionsRef: Actions;

function start(model: ModelFile): void {
  state = {
    model,
    benchmark: pendingBenchmark,
    input: EXAMPLE_BATCH,
    alphaIndex: ALPHAS.indexOf(0.1),
    results: [],
    selected: null,
    picked: null,
    paretoX: "bbb",
    paretoY: "cpp",
    showGhosts: true,
  };
  root.innerHTML = `
    <header class="top">
      <div class="title-row">
        <div>
          <h1>Peptide triage for glioblastoma</h1>
          <p class="sub">Blood–brain-barrier and cell penetration, with a conformal
          <em>I don't know</em>. Every number below is either measured on held-out data or a
          named heuristic — nothing is a black box.</p>
        </div>
      </div>
      <nav class="tabs" role="tablist">
        ${TABS.map(
          (t) =>
            `<button role="tab" id="tab-${t.id}" aria-controls="panel" data-tab="${t.id}" class="tab">
              ${t.label}<small>${t.blurb}</small>
            </button>`,
        ).join("")}
      </nav>
      <div class="dial-bar">
        <label class="dial">
          <span>coverage target <strong id="dial-coverage">90%</strong>
            <span class="hint">(α = <span id="dial-alpha">0.10</span>)</span></span>
          <input type="range" id="dial" min="0" max="${ALPHAS.length - 1}" step="1"
            value="${state.alphaIndex}" aria-label="conformal coverage target">
          <span class="dial-scale"><i>α = 0.40 · looser</i><i>α = 0.05 · tighter</i></span>
        </label>
        <p class="hint" id="dial-note">Loading measured dial behaviour…</p>
      </div>
    </header>
    <main id="panel" role="tabpanel"></main>
    <footer class="bottom">
      Trained on B3Pdb/B3Pred peptides (Kumar V. et al., Pharmaceutics 2021, 13(8):1237).
      Heuristic indexes are rules, not models. Not a clinical tool — a screening aid that
      shows its reasoning and refuses when it should.
    </footer>`;

  const actions: Actions = {
    setInput(text) {
      state.input = text;
    },
    analyze() {
      state.results = analyzeBatch(state.model, parseInput(state.input), state.alphaIndex);
      state.selected = null;
      state.picked = null;
      render();
    },
    setAlpha(i) {
      state.alphaIndex = i;
      if (state.results.length) {
        state.results = analyzeBatch(state.model, parseInput(state.input), i);
      }
      updateDial();
      render();
    },
    select(i) {
      state.selected = i;
      render();
    },
    pick(i) {
      state.picked = i;
      render();
    },
    setAxis(axis, key) {
      if (axis === "x") state.paretoX = key;
      else state.paretoY = key;
      render();
    },
    toggleGhosts() {
      state.showGhosts = !state.showGhosts;
      render();
    },
    reRender: render,
    goTab(t) {
      tab = t;
      render();
    },
  };

  root.querySelectorAll<HTMLElement>("[data-tab]").forEach((el) =>
    el.addEventListener("click", () => {
      tab = el.dataset.tab as TabId;
      render();
    }),
  );
  actionsRef = actions;
  root.querySelector<HTMLInputElement>("#dial")!.addEventListener("input", (e) =>
    actions.setAlpha(Number((e.target as HTMLInputElement).value)),
  );
  document.addEventListener("keydown", (e) => {
    if ((e.metaKey || e.ctrlKey) && e.key === "Enter") {
      e.preventDefault();
      actions.analyze();
    }
  });

  // open on a real result rather than an empty box
  actions.analyze();
}

function updateDial(): void {
  const alpha = ALPHAS[state.alphaIndex];
  const coverage = document.getElementById("dial-coverage");
  const alphaEl = document.getElementById("dial-alpha");
  const note = document.getElementById("dial-note");
  if (coverage) coverage.textContent = pct(1 - alpha);
  if (alphaEl) alphaEl.textContent = alpha.toFixed(2);
  if (!note) return;
  const b = state.benchmark;
  if (!b) {
    note.textContent = "Benchmark still loading — the dial still works; the measured numbers arrive with benchmark.json.";
    return;
  }
  const pick = (arr: Benchmark["tasks"]["bbb"]["similarity"]["alpha_sweep"]) =>
    arr.reduce((a, c) => (Math.abs(c.alpha - alpha) < Math.abs(a.alpha - alpha) ? c : a));
  const bbbSweep = b.tasks.bbb.similarity.alpha_sweep;
  const cppSweep = b.tasks.cpp.similarity.alpha_sweep;
  const bbb = pick(bbbSweep);
  const cpp = pick(cppSweep);
  const first = bbbSweep[0];
  const last = bbbSweep[bbbSweep.length - 1];
  note.textContent =
    `measured on held-out clusters at α=${bbb.alpha}: BBB leaves ${pct(bbb.abstain_rate)} unanswered ` +
    `and is wrong on ${pct(bbb.error_rate)} of the answers it gives; cell penetration leaves ` +
    `${pct(cpp.abstain_rate)} unanswered and is wrong on ${pct(cpp.error_rate)}. Across the whole dial ` +
    `(α ${first.alpha} → ${last.alpha}) BBB goes from ${pct(first.abstain_rate)} to ${pct(last.abstain_rate)} ` +
    `refused and from ${pct(first.error_rate)} to ${pct(last.error_rate)} wrong — more refusals, fewer ` +
    `mistakes. Individual steps are not monotone: each α lands on a different empirical quantile of a ` +
    `small calibration set.`;
}

function render(): void {
  const panel = document.getElementById("panel");
  if (!panel) return;
  document.querySelectorAll<HTMLElement>("[data-tab]").forEach((el) => {
    const active = el.dataset.tab === tab;
    el.classList.toggle("active", active);
    el.setAttribute("aria-selected", String(active));
  });
  if (tab === "predict") renderPredict(panel, state, actionsRef);
  else if (tab === "pareto") renderPareto(panel, state, actionsRef);
  else if (tab === "validation") renderValidation(panel, state);
  else renderMethods(panel, state.model);
}

boot();
